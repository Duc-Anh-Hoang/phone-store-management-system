CREATE TABLE PhanQuyen (
    MAQUYEN  VARCHAR(10),
    TENQUYEN NVARCHAR(50)  NOT NULL,
    MOTA     NVARCHAR(255) NULL,
    CONSTRAINT PK_PhanQuyen PRIMARY KEY (MAQUYEN),
    CONSTRAINT UQ_PhanQuyen_Ten UNIQUE (TENQUYEN)
);

CREATE TABLE NhanVien (
    MANV       VARCHAR(10),
    HOTEN      NVARCHAR(100) NOT NULL,
    CHUCVU     NVARCHAR(50)  NOT NULL,
    SDT        VARCHAR(15)   NULL,
    EMAIL      NVARCHAR(100) NULL,
    NGAYVAOLAM DATETIME      NOT NULL DEFAULT GETDATE(),
    TRANGTHAI  VARCHAR(10)   NOT NULL DEFAULT 'dang_lam',
    CONSTRAINT PK_NhanVien PRIMARY KEY (MANV),
    CONSTRAINT CK_NhanVien_ChucVu CHECK (CHUCVU IN (N'Quản lý', N'Bán hàng', N'Thu ngân', N'Kho', N'Kỹ thuật & Bảo hành')),
    CONSTRAINT CK_NhanVien_TrangThai CHECK (TRANGTHAI IN ('dang_lam', 'da_nghi'))
);

CREATE TABLE TaiKhoan (
    USERNAME      VARCHAR(50),
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    MANV          VARCHAR(10)  NOT NULL,
    MAQUYEN       VARCHAR(10)  NOT NULL,
    TRANGTHAI     VARCHAR(10)  NOT NULL DEFAULT 'hoat_dong',
    NGAYTAO       DATETIME     NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_TaiKhoan PRIMARY KEY (USERNAME),
    CONSTRAINT UQ_TaiKhoan_MaNV UNIQUE (MANV),
    CONSTRAINT FK_TaiKhoan_NhanVien FOREIGN KEY (MANV) REFERENCES NhanVien(MANV),
    CONSTRAINT FK_TaiKhoan_PhanQuyen FOREIGN KEY (MAQUYEN) REFERENCES PhanQuyen(MAQUYEN),
    CONSTRAINT CK_TaiKhoan_TrangThai CHECK (TRANGTHAI IN ('hoat_dong', 'bi_khoa'))
);

CREATE TABLE NhomHang (
    MANHOM  VARCHAR(10),
    TENNHOM NVARCHAR(50) NOT NULL,
    CONSTRAINT PK_NhomHang PRIMARY KEY (MANHOM),
    CONSTRAINT UQ_NhomHang_TenNhom UNIQUE (TENNHOM)
);

CREATE TABLE LoaiHang (
    MALOAI  VARCHAR(10),
    TENLOAI NVARCHAR(50) NOT NULL,
    CONSTRAINT PK_LoaiHang PRIMARY KEY (MALOAI),
    CONSTRAINT UQ_LoaiHang_TenLoai UNIQUE (TENLOAI)
);

CREATE TABLE ThuocTinh (
    MATHUOCTINH  VARCHAR(10),
    TENTHUOCTINH NVARCHAR(50) NOT NULL,
    CONSTRAINT PK_ThuocTinh PRIMARY KEY (MATHUOCTINH)
);

CREATE TABLE MatHang (
    MAHANG          VARCHAR(10),
    TENHANG         NVARCHAR(100) NOT NULL,
    DONGIA          DECIMAL(18,2) NOT NULL,
    DVT             NVARCHAR(20)  NOT NULL DEFAULT N'Cái',
    MANHOM          VARCHAR(10)   NOT NULL,
    MALOAI          VARCHAR(10)   NOT NULL,
    QUANLYIMEI      BIT           NOT NULL,
    THOIHANBAOHANH  INT           NOT NULL,
    CONSTRAINT PK_MatHang PRIMARY KEY (MAHANG),
    CONSTRAINT FK_MatHang_NhomHang FOREIGN KEY (MANHOM) REFERENCES NhomHang(MANHOM),
    CONSTRAINT FK_MatHang_LoaiHang FOREIGN KEY (MALOAI) REFERENCES LoaiHang(MALOAI),
    CONSTRAINT CK_MatHang_DonGia CHECK (DONGIA > 0),
    CONSTRAINT CK_MatHang_BaoHanh CHECK (THOIHANBAOHANH >= 0 AND (QUANLYIMEI = 1 OR THOIHANBAOHANH = 0))
);

CREATE TABLE ChiTietThuocTinh (
    MAHANG      VARCHAR(10),
    MATHUOCTINH VARCHAR(10),
    GIA_TRI     NVARCHAR(100) NOT NULL,
    CONSTRAINT PK_ChiTietThuocTinh PRIMARY KEY (MAHANG, MATHUOCTINH),
    CONSTRAINT FK_CTTT_MatHang FOREIGN KEY (MAHANG) REFERENCES MatHang(MAHANG),
    CONSTRAINT FK_CTTT_ThuocTinh FOREIGN KEY (MATHUOCTINH) REFERENCES ThuocTinh(MATHUOCTINH)
);

CREATE TABLE NhaCungCap (
    MANCC  VARCHAR(10),
    TENNCC NVARCHAR(100) NOT NULL,
    DIACHI NVARCHAR(255) NULL,
    SDT    VARCHAR(15)   NULL,
    EMAIL  NVARCHAR(100) NULL,
    CONSTRAINT PK_NhaCungCap PRIMARY KEY (MANCC),
    CONSTRAINT CK_NhaCungCap_SDT CHECK (LEN(SDT) >= 10)
);

CREATE TABLE PhieuNhap (
    SOPN     VARCHAR(15),
    NGAYNHAP DATETIME    NOT NULL DEFAULT GETDATE(),
    MANCC    VARCHAR(10) NOT NULL,
    MANV     VARCHAR(10) NOT NULL,
    CONSTRAINT PK_PhieuNhap PRIMARY KEY (SOPN),
    CONSTRAINT FK_PhieuNhap_NhaCungCap FOREIGN KEY (MANCC) REFERENCES NhaCungCap(MANCC),
    CONSTRAINT FK_PhieuNhap_NhanVien   FOREIGN KEY (MANV)  REFERENCES NhanVien(MANV)
);

CREATE TABLE ChiTietPhieuNhap (
    SOPN        VARCHAR(15),
    MAHANG      VARCHAR(10),
    SLNHAP      INT           NOT NULL,
    DONGIA_NHAP DECIMAL(18,2) NOT NULL,
    CONSTRAINT PK_ChiTietPhieuNhap PRIMARY KEY (SOPN, MAHANG),
    CONSTRAINT FK_CTPN_PhieuNhap FOREIGN KEY (SOPN)   REFERENCES PhieuNhap(SOPN),
    CONSTRAINT FK_CTPN_MatHang   FOREIGN KEY (MAHANG) REFERENCES MatHang(MAHANG),
    CONSTRAINT CK_CTPN_SoLuong CHECK (SLNHAP > 0),
    CONSTRAINT CK_CTPN_DonGia  CHECK (DONGIA_NHAP > 0)
);

CREATE TABLE IMEI (
    MAIMEI    VARCHAR(20),
    MAHANG    VARCHAR(10) NOT NULL,
    SOPN      VARCHAR(15) NOT NULL,
    SOIMEI    VARCHAR(20) NOT NULL,
    TRANGTHAI VARCHAR(20) NOT NULL DEFAULT 'con_hang',
    CONSTRAINT PK_IMEI PRIMARY KEY (MAIMEI),
    CONSTRAINT UQ_IMEI_SoIMEI UNIQUE (SOIMEI),
    CONSTRAINT UQ_IMEI_MaImei_MaHang UNIQUE (MAIMEI, MAHANG),
    CONSTRAINT FK_IMEI_CTPN FOREIGN KEY (SOPN, MAHANG) REFERENCES ChiTietPhieuNhap(SOPN, MAHANG),
    CONSTRAINT CK_IMEI_SoIMEI CHECK (LEN(SOIMEI) = 15 AND SOIMEI NOT LIKE '%[^0-9]%'),
    CONSTRAINT CK_IMEI_TrangThai CHECK (TRANGTHAI IN ('con_hang', 'da_ban', 'tra_hang'))
);

CREATE TABLE KhachHang (
    MAKH   VARCHAR(10),
    HOTEN  NVARCHAR(100) NOT NULL,
    DIACHI NVARCHAR(255) NULL,
    SDT    VARCHAR(15)   NULL,
    EMAIL  NVARCHAR(100) NULL,
    CONSTRAINT PK_KhachHang PRIMARY KEY (MAKH)
);

CREATE TABLE KhuyenMai (
    MAKM         VARCHAR(10),
    TENKM        NVARCHAR(100) NOT NULL,
    PHANTRAMGIAM DECIMAL(5,2)  NOT NULL,
    NGAYBD       DATETIME      NOT NULL,
    NGAYKT       DATETIME      NOT NULL,
    TAMDUNG      BIT           NOT NULL DEFAULT 0,
    CONSTRAINT PK_KhuyenMai PRIMARY KEY (MAKM),
    CONSTRAINT CK_KhuyenMai_PhanTram CHECK (PHANTRAMGIAM > 0 AND PHANTRAMGIAM <= 100),
    CONSTRAINT CK_KhuyenMai_NgayKT   CHECK (NGAYKT > NGAYBD)
);

CREATE TABLE HoaDon (
    SOHD                VARCHAR(15),
    NGAYLAP             DATETIME      NOT NULL DEFAULT GETDATE(),
    MAKH                VARCHAR(10)   NULL,
    MANV                VARCHAR(10)   NOT NULL,
    MAKM                VARCHAR(10)   NULL,
    KENHBAN             VARCHAR(10)   NOT NULL DEFAULT 'tai_quay',
    TONGTIEN            DECIMAL(18,2) NOT NULL DEFAULT 0,
    TIENGIAMGIA         DECIMAL(18,2) NOT NULL DEFAULT 0,
    THANHTIEN           AS (TONGTIEN - TIENGIAMGIA) PERSISTED,
    PHUONGTHUCTHANHTOAN VARCHAR(20)   NOT NULL,
    CONSTRAINT PK_HoaDon PRIMARY KEY (SOHD),
    CONSTRAINT FK_HoaDon_KhachHang FOREIGN KEY (MAKH) REFERENCES KhachHang(MAKH),
    CONSTRAINT FK_HoaDon_NhanVien  FOREIGN KEY (MANV) REFERENCES NhanVien(MANV),
    CONSTRAINT FK_HoaDon_KhuyenMai FOREIGN KEY (MAKM) REFERENCES KhuyenMai(MAKM),
    CONSTRAINT CK_HoaDon_TongTien  CHECK (TONGTIEN >= 0),
    CONSTRAINT CK_HoaDon_TienGiam  CHECK (TIENGIAMGIA >= 0 AND TIENGIAMGIA <= TONGTIEN),
    CONSTRAINT CK_HoaDon_KenhBan CHECK (KENHBAN IN ('tai_quay', 'online')),
    CONSTRAINT CK_HoaDon_PhuongThuc CHECK (PHUONGTHUCTHANHTOAN IN ('tien_mat', 'chuyen_khoan', 'the'))
);

CREATE TABLE ChiTietHoaDon (
    MACTHD     INT IDENTITY(1,1),
    SOHD       VARCHAR(15)   NOT NULL,
    MAHANG     VARCHAR(10)   NOT NULL,
    MAIMEI     VARCHAR(20)   NULL,
    SLBAN      INT           NOT NULL,
    DONGIA_BAN DECIMAL(18,2) NOT NULL,
    CONSTRAINT PK_ChiTietHoaDon PRIMARY KEY (MACTHD),
    CONSTRAINT FK_CTHD_HoaDon  FOREIGN KEY (SOHD)   REFERENCES HoaDon(SOHD),
    CONSTRAINT FK_CTHD_MatHang FOREIGN KEY (MAHANG) REFERENCES MatHang(MAHANG),
    CONSTRAINT FK_CTHD_IMEI    FOREIGN KEY (MAIMEI, MAHANG) REFERENCES IMEI(MAIMEI, MAHANG),
    CONSTRAINT CK_CTHD_SoLuong CHECK (SLBAN > 0),
    CONSTRAINT CK_CTHD_IMEI_SoLuong CHECK (MAIMEI IS NULL OR SLBAN = 1),
    CONSTRAINT CK_CTHD_DonGia  CHECK (DONGIA_BAN > 0)
);

CREATE TABLE BaoHanh (
    MABH         VARCHAR(15),
    SOHD         VARCHAR(15)   NOT NULL,
    MAIMEI       VARCHAR(20)   NOT NULL,
    NGAYBD       DATETIME      NOT NULL,
    THOIHANTHANG INT           NOT NULL,
    NGAYKT       AS DATEADD(MONTH, THOIHANTHANG, NGAYBD) PERSISTED,
    DIEUKIEN     NVARCHAR(255) NULL,
    CONSTRAINT PK_BaoHanh PRIMARY KEY (MABH),
    CONSTRAINT UQ_BaoHanh_MaImei UNIQUE (MAIMEI),
    CONSTRAINT FK_BaoHanh_HoaDon FOREIGN KEY (SOHD)   REFERENCES HoaDon(SOHD),
    CONSTRAINT FK_BaoHanh_IMEI   FOREIGN KEY (MAIMEI) REFERENCES IMEI(MAIMEI),
    CONSTRAINT CK_BaoHanh_ThoiHan CHECK (THOIHANTHANG > 0)
);

CREATE TABLE TraHang (
    MATR             VARCHAR(15),
    SOHD             VARCHAR(15)   NOT NULL,
    MAIMEI           VARCHAR(20)   NOT NULL,
    NGAYTR           DATETIME      NOT NULL DEFAULT GETDATE(),
    LYDO             NVARCHAR(255) NOT NULL,
    HINHTHUCHOANTIEN VARCHAR(20)   NOT NULL,
    MANV             VARCHAR(10)   NOT NULL,
    CONSTRAINT PK_TraHang PRIMARY KEY (MATR),
    CONSTRAINT UQ_TraHang_MaImei UNIQUE (MAIMEI),
    CONSTRAINT FK_TraHang_HoaDon   FOREIGN KEY (SOHD)   REFERENCES HoaDon(SOHD),
    CONSTRAINT FK_TraHang_IMEI     FOREIGN KEY (MAIMEI) REFERENCES IMEI(MAIMEI),
    CONSTRAINT FK_TraHang_NhanVien FOREIGN KEY (MANV)   REFERENCES NhanVien(MANV),
    CONSTRAINT CK_TraHang_HinhThuc CHECK (HINHTHUCHOANTIEN IN ('tien_mat', 'chuyen_khoan', 'doi_hang'))
);

CREATE TABLE PhieuTiepNhanBaoHanh (
    MATN            VARCHAR(15),
    MABH            VARCHAR(15)   NOT NULL,
    NGAYNHAN        DATETIME      NOT NULL DEFAULT GETDATE(),
    TINHTRANGLOI    NVARCHAR(255) NOT NULL,
    MANV_TIEPNHAN   VARCHAR(10)   NOT NULL,
    MANV_KYTHUAT    VARCHAR(10)   NULL,
    NGAYHENTRA      DATETIME      NULL,
    NGAYTRA         DATETIME      NULL,
    KETQUA          NVARCHAR(255) NULL,
    CHIPHI          DECIMAL(18,2) NOT NULL DEFAULT 0,
    TRANGTHAI       VARCHAR(20)   NOT NULL DEFAULT 'tiep_nhan',
    CONSTRAINT PK_PhieuTiepNhanBaoHanh PRIMARY KEY (MATN),
    CONSTRAINT FK_TiepNhan_BaoHanh FOREIGN KEY (MABH) REFERENCES BaoHanh(MABH),
    CONSTRAINT FK_TiepNhan_NVTiepNhan FOREIGN KEY (MANV_TIEPNHAN) REFERENCES NhanVien(MANV),
    CONSTRAINT FK_TiepNhan_NVKyThuat FOREIGN KEY (MANV_KYTHUAT) REFERENCES NhanVien(MANV),
    CONSTRAINT CK_TiepNhan_ChiPhi CHECK (CHIPHI >= 0),
    CONSTRAINT CK_TiepNhan_NgayHenTra CHECK (NGAYHENTRA IS NULL OR NGAYHENTRA >= NGAYNHAN),
    CONSTRAINT CK_TiepNhan_NgayTra CHECK (NGAYTRA IS NULL OR NGAYTRA >= NGAYNHAN),
    CONSTRAINT CK_TiepNhan_TrangThai CHECK (TRANGTHAI IN ('tiep_nhan', 'dang_sua', 'cho_linh_kien', 'hoan_thanh', 'da_tra'))
);

CREATE TABLE DonHangOnline (
    MADH                VARCHAR(15),
    NGAYDAT             DATETIME      NOT NULL DEFAULT GETDATE(),
    MAKH                VARCHAR(10)   NOT NULL,
    TENNGUOINHAN        NVARCHAR(100) NOT NULL,
    SDTNGUOINHAN        VARCHAR(15)   NOT NULL,
    DIACHIGIAO          NVARCHAR(255) NOT NULL,
    PHUONGTHUCTHANHTOAN VARCHAR(20)   NOT NULL,
    TONGTIEN            DECIMAL(18,2) NOT NULL DEFAULT 0,
    TRANGTHAI           VARCHAR(20)   NOT NULL DEFAULT 'cho_xac_nhan',
    MANV                VARCHAR(10)   NULL,
    SOHD                VARCHAR(15)   NULL,
    CONSTRAINT PK_DonHangOnline PRIMARY KEY (MADH),
    CONSTRAINT FK_DHOL_KhachHang FOREIGN KEY (MAKH) REFERENCES KhachHang(MAKH),
    CONSTRAINT FK_DHOL_NhanVien  FOREIGN KEY (MANV) REFERENCES NhanVien(MANV),
    CONSTRAINT FK_DHOL_HoaDon    FOREIGN KEY (SOHD) REFERENCES HoaDon(SOHD),
    CONSTRAINT CK_DHOL_TongTien CHECK (TONGTIEN >= 0),
    CONSTRAINT CK_DHOL_PhuongThuc CHECK (PHUONGTHUCTHANHTOAN IN ('cod', 'chuyen_khoan', 'the')),
    CONSTRAINT CK_DHOL_TrangThai CHECK (TRANGTHAI IN ('cho_xac_nhan', 'da_xac_nhan', 'dang_giao', 'hoan_thanh', 'da_huy'))
);

CREATE TABLE ChiTietDonHangOnline (
    MADH    VARCHAR(15),
    MAHANG  VARCHAR(10),
    SOLUONG INT           NOT NULL,
    DONGIA  DECIMAL(18,2) NOT NULL,
    CONSTRAINT PK_ChiTietDonHangOnline PRIMARY KEY (MADH, MAHANG),
    CONSTRAINT FK_CTDHOL_DonHang FOREIGN KEY (MADH)   REFERENCES DonHangOnline(MADH),
    CONSTRAINT FK_CTDHOL_MatHang FOREIGN KEY (MAHANG) REFERENCES MatHang(MAHANG),
    CONSTRAINT CK_CTDHOL_SoLuong CHECK (SOLUONG > 0),
    CONSTRAINT CK_CTDHOL_DonGia  CHECK (DONGIA > 0)
);

CREATE TABLE ThamSo (
    MATHAMSO  VARCHAR(30),
